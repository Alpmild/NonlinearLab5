import numpy as np

NAME_ERROR = "Ошибка KD"


def kd(f, u0, t0, t1, h, a1, a2, a3, s=0.5):
    """
    Универсальный KD-метод с тем же интерфейсом, что и RK4/Euler:

        kd(f, u0, t0, t1, h, a1, a2, a3)

    В отличие от старого KD, здесь f реально используется.

    Метод построен как композиция двух полушагов:
    1) явный полушаг;
    2) диагонально-неявный полушаг.

    Неявность учитывает только диагональ якобиана f.
    Для Sprott Case B это даёт тот же знаменатель (1 + a2*h2)
    в уравнении y.
    """

    n = int(round((t1 - t0) / h))

    t = t0 + h * np.arange(n + 1)
    u = np.zeros((n + 1, len(u0)))
    u[0] = u0

    h1 = h * s
    h2 = h * (1.0 - s)

    eps = 1e-7

    for i in range(n):
        ui = u[i].copy()

        # ----------------------------------------------------------
        # 1. Первый полушаг: явный последовательный шаг
        # ----------------------------------------------------------
        v = ui.copy()

        for j in range(len(u0)):
            fj = f(v, a1, a2, a3)[j]
            v[j] = v[j] + h1 * fj

        # ----------------------------------------------------------
        # 2. Второй полушаг: диагонально-неявный шаг
        # ----------------------------------------------------------
        w = v.copy()

        # Начальное приближение для неявного шага
        fw = f(w, a1, a2, a3)
        for j in range(len(u0)):
            w[j] = w[j] + h2 * fw[j]

        # Несколько итераций по диагонали якобиана
        for _ in range(4):
            fw = f(w, a1, a2, a3)

            for j in range(len(u0)):
                # численная оценка диагонали якобиана df_j/du_j
                wp = w.copy()
                wm = w.copy()

                delta = eps * max(1.0, abs(w[j]))
                wp[j] += delta
                wm[j] -= delta

                fp = f(wp, a1, a2, a3)[j]
                fm = f(wm, a1, a2, a3)[j]

                djj = (fp - fm) / (2.0 * delta)

                # Решаем скалярное неявное уравнение:
                # w_new[j] = v[j] + h2 * f_j(w_new)
                #
                # Линеаризуем только по диагонали:
                # f_j(w_new) ≈ f_j(w) + djj*(w_new[j]-w[j])

                denom = 1.0 - h2 * djj

                if abs(denom) < 1e-14:
                    w[j] = v[j] + h2 * fw[j]
                else:
                    w[j] = (v[j] + h2 * (fw[j] - djj * w[j])) / denom

        u[i + 1] = w

    return t, u